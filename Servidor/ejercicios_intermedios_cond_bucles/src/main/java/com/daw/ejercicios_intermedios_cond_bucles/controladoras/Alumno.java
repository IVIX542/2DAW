package com.daw.ejercicios_intermedios_cond_bucles.controladoras;

public class Alumno {

    public Integer id;
    public String nombre;
    public Double nota;
    public boolean aprobado;

    public Alumno(Integer id, String nombre, Double nota, boolean aprobado) {
        this.id = id;
        this.nombre = nombre;
        this.nota = nota;
        this.aprobado = aprobado;
    }

}
